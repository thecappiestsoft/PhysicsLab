#!/usr/bin/env node
/**
 * PhysicsLab — build script.
 *
 * Reads index.html (repository root), inlines every <link rel="stylesheet" href="…"> and
 * <script src="…"></script> it references (in the same order), and writes a
 * single self-contained file: dist/PhysicsLab.html.
 *
 * No dependencies — plain Node.js (>= 18).
 *
 *   node tools/build.mjs            → dist/PhysicsLab.html
 *   node tools/build.mjs --minify   → also strips comments/indentation (light, safe)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = root; // the site lives in the repository root (GitHub Pages)
const outDir = join(root, 'dist');
const outFile = join(outDir, 'PhysicsLab.html');
const minify = process.argv.includes('--minify');

const read = rel => {
  const p = join(srcDir, rel);
  if (!existsSync(p)) throw new Error(`Missing file referenced from index.html: ${rel}`);
  return readFileSync(p, 'utf8');
};

const stripJs = code =>
  code
    .replace(/^\s*\/\*\*[\s\S]*?\*\/\s*$/gm, '') // file-level JSDoc blocks
    .replace(/^\s+/gm, '')
    .replace(/\n{2,}/g, '\n');
const stripCss = code =>
  code
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s+/gm, '')
    .replace(/\n{2,}/g, '\n');

let html = read('index.html');
let css = 0,
  js = 0;

html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => {
  css++;
  const code = read(href);
  return `<style data-src="${href}">\n${minify ? stripCss(code) : code}</style>`;
});

// Favicon → data URI, so the single file needs nothing next to it.
html = html.replace(/<link rel="icon" href="([^"]+\.svg)"([^>]*)>/, (m, href, rest) => {
  const p = join(srcDir, href);
  if (!existsSync(p)) return m;
  return `<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(readFileSync(p, 'utf8'))}"${rest}>`;
});

// Keep "</script" sequences inside code from closing the inline tag.
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  js++;
  const code = read(src).replace(/<\/script/gi, '<\\/script');
  return `<script data-src="${src}">\n${minify ? stripJs(code) : code}</script>`;
});

const stamp = new Date().toISOString().replace('T', ' ').slice(0, 16);
html = html.replace(
  '<head>',
  `<head>\n<!-- PhysicsLab — built ${stamp} UTC from the repository sources (do not edit this file; edit the sources and run npm run build) -->`
);

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, html);
console.log(
  `✔ ${outFile}\n  ${css} stylesheets + ${js} scripts inlined, ${(html.length / 1024).toFixed(0)} KB`
);
